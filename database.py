def leaderboard(limit=10):
    with get_db() as db:
        rows = db.execute(
            "SELECT username, xp, streak FROM users ORDER BY xp DESC, username LIMIT ?",
            (limit,),
        ).fetchall()
        return [dict(r) for r in rows]


def username_taken(username, exclude_user_id=None):
    """True if the name belongs to somebody else. Case-insensitive on both
    backends — citext on Postgres, COLLATE NOCASE on SQLite."""
    with get_db() as db:
        row = db.execute("SELECT id FROM users WHERE username = ?",
                         (username,)).fetchone()
    return bool(row) and row["id"] != exclude_user_id


def update_profile(user_id, username=None, avatar_url=None, display_name=None):
    """Update the fields a learner is allowed to change about themselves."""
    sets, params = [], []
    if username is not None:
        sets.append("username = ?"); params.append(username)
    if avatar_url is not None:
        sets.append("avatar_url = ?"); params.append(avatar_url)
    if display_name is not None:
        sets.append("display_name = ?"); params.append(display_name)
    if not sets:
        return False
    params.append(user_id)
    with get_db() as db:
        db.execute("UPDATE users SET %s WHERE id = ?" % ", ".join(sets), tuple(params))
    return True


def export_user(user_id):
    """Everything held about one person, for the data-export right.

    Deliberately assembled here rather than in a route so the shape cannot
    drift from what delete_user removes.
    """
    with get_db() as db:
        u = db.execute(
            "SELECT id, username, email, xp, streak, last_active, created_at, "
            "google_sub, avatar_url, google_avatar, display_name, is_admin "
            "FROM users WHERE id = ?",
            (user_id,)).fetchone()
        if not u:
            return None
        lessons = db.execute(
            "SELECT course_slug, lesson_slug, completed_at FROM lesson_progress "
            "WHERE user_id = ? ORDER BY completed_at", (user_id,)).fetchall()
        challenges = db.execute(
            "SELECT challenge_slug, completed_at FROM challenge_progress "
            "WHERE user_id = ? ORDER BY completed_at", (user_id,)).fetchall()
        achievements = db.execute(
            "SELECT achievement_id, earned_at FROM user_achievements "
            "WHERE user_id = ? ORDER BY earned_at", (user_id,)).fetchall()
    return {
        "account": dict(u),
        "lesson_progress": [dict(r) for r in lessons],
        "challenge_progress": [dict(r) for r in challenges],
        "achievements": [dict(r) for r in achievements],
    }


def delete_user(user_id):
    """Erase a person and everything attached to them. Returns True if a
    row went.

    Children are removed explicitly rather than relying on ON DELETE
    CASCADE: Postgres declares it, the SQLite schema does not, and SQLite
    only enforces foreign keys when the pragma is on. Doing it by hand
    behaves identically on both.
    """
    with get_db() as db:
        for table in ("lesson_progress", "challenge_progress", "user_achievements"):
            db.execute("DELETE FROM %s WHERE user_id = ?" % table, (user_id,))
        cur = db.execute("DELETE FROM users WHERE id = ?", (user_id,))
        return cur.rowcount > 0


# ── admin portal ─────────────────────────────────────────────────────

def set_admin(username_or_email, is_admin=True):
    """Grant/revoke admin. Returns True if a row was changed."""
    with get_db() as db:
        cur = db.execute(
            "UPDATE users SET is_admin = ? WHERE username = ? OR email = ?",
            (1 if is_admin else 0, username_or_email, username_or_email),
        )
        return cur.rowcount > 0


SORTS = {
    "xp": "u.xp DESC",
    "recent": "COALESCE(u.last_active, u.created_at) DESC",
    "joined": "u.created_at DESC",
    "lessons": "lessons_done DESC",
    "streak": "u.streak DESC",
    "name": "u.username ASC" if IS_PG else "u.username COLLATE NOCASE ASC",
}


def list_members(search="", sort="recent", limit=200, offset=0):
    """Member roster with progress rolled up. Never returns password hashes."""
    order = SORTS.get(sort, SORTS["recent"])
    where, params = "", []
    if search:
        like = "ILIKE" if IS_PG else "LIKE"
        where = f"WHERE u.username {like} ? OR u.email {like} ?"
        params = [f"%{search}%", f"%{search}%"]
    sql = f"""
        SELECT u.id, u.username, u.email, u.xp, u.streak, u.last_active,
               u.created_at, u.is_admin, u.google_sub, u.avatar_url,
               (SELECT COUNT(*) FROM lesson_progress p WHERE p.user_id = u.id)
                   AS lessons_done,
               (SELECT COUNT(*) FROM challenge_progress c WHERE c.user_id = u.id)
                   AS challenges_done,
               (SELECT COUNT(*) FROM user_achievements a WHERE a.user_id = u.id)
                   AS achievements,
               (SELECT MAX(completed_at) FROM lesson_progress p WHERE p.user_id = u.id)
                   AS last_lesson_at
        FROM users u {where}
        ORDER BY {order}
        LIMIT ? OFFSET ?
    """
    with get_db() as db:
        rows = db.execute(sql, (*params, limit, offset)).fetchall()
        total = db.execute(
            f"SELECT COUNT(*) AS n FROM users u {where}", params
        ).fetchone()["n"]
    return [dict(r) for r in rows], total


def member_detail(user_id):
    """Everything the portal shows for one member (no credentials)."""
    with get_db() as db:
        u = db.execute(
            """SELECT id, username, email, xp, streak, last_active, created_at,
                      is_admin, google_sub, avatar_url
               FROM users WHERE id = ?""", (user_id,)
        ).fetchone()
        if not u:
            return None
        lessons = db.execute(
            """SELECT course_slug, lesson_slug, completed_at
               FROM lesson_progress WHERE user_id = ?
               ORDER BY completed_at DESC""", (user_id,)
        ).fetchall()
        challenges = db.execute(
            """SELECT challenge_slug, completed_at
               FROM challenge_progress WHERE user_id = ?
               ORDER BY completed_at DESC""", (user_id,)
        ).fetchall()
        achievements = db.execute(
            "SELECT achievement_id, earned_at FROM user_achievements WHERE user_id = ?"
            " ORDER BY earned_at DESC", (user_id,)
        ).fetchall()
    return {
        "user": dict(u),
        "lessons": [dict(r) for r in lessons],
        "challenges": [dict(r) for r in challenges],
        "achievements": [dict(r) for r in achievements],
    }


def platform_stats():
    """Headline numbers for the admin overview."""
    with get_db() as db:
        one = lambda q, p=(): db.execute(q, p).fetchone()[0]
        return {
            "members": one("SELECT COUNT(*) FROM users"),
            "admins": one("SELECT COUNT(*) FROM users WHERE is_admin = 1"),
            "google_members": one("SELECT COUNT(*) FROM users WHERE google_sub IS NOT NULL"),
            "new_7d": one("SELECT COUNT(*) FROM users WHERE created_at >= ?",
                          (_days_ago(7),)),
            "active_7d": one("SELECT COUNT(*) FROM users WHERE last_active >= ?",
                             ((date.today() - timedelta(days=7)).isoformat(),)),
            "active_today": one("SELECT COUNT(*) FROM users WHERE last_active = ?",
                                (date.today().isoformat(),)),
            "lessons_completed": one("SELECT COUNT(*) FROM lesson_progress"),
            "challenges_completed": one("SELECT COUNT(*) FROM challenge_progress"),
            "total_xp": one("SELECT COALESCE(SUM(xp), 0) FROM users"),
            "learners_with_progress": one(
                "SELECT COUNT(DISTINCT user_id) FROM lesson_progress"),
        }


def signups_by_day(days=14):
    with get_db() as db:
        rows = db.execute(
            """SELECT substr(created_at, 1, 10) AS day, COUNT(*) AS n FROM users
               WHERE created_at >= ?
               GROUP BY day ORDER BY day""", (_days_ago(days),)
        ).fetchall()
    return [dict(r) for r in rows]


def course_engagement():
    """Which courses learners actually work through."""
    with get_db() as db:
        rows = db.execute(
            """SELECT course_slug, COUNT(*) AS completions,
                      COUNT(DISTINCT user_id) AS learners
               FROM lesson_progress GROUP BY course_slug
               ORDER BY completions DESC"""
        ).fetchall()
    return [dict(r) for r in rows]
